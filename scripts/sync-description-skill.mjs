// Regenerates the skill constants from their SKILL.md files (the one source each).
// The relay and bridge ship as single bundles and Convex cannot read files, so the text travels as a TS string.
// Run `pnpm sync:skills` after editing a skill; packages/core/test/descriptionSkill.test.ts,
// packages/core/test/researchSkills.test.ts and apps/ingest/test/radar.test.ts fail until you do.
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const SKILLS = [
  {
    skill: "rlr-description-safety",
    name: "DESCRIPTION_SKILL_TEXT",
    what: "how to write a public Mixcloud description",
    // The bridge gets its own copy: it is built with tsc and deployed without @aircheck/core (a dev dependency).
    outs: ["packages/core/src/package/descriptionSkill.ts", "apps/bridge/src/descriptionSkill.ts"],
  },
  {
    skill: "rlr-email-extraction-safety",
    name: "EXTRACTION_SKILL_TEXT",
    what: "the release radar extractor's fixed instruction (Plan 8)",
    outs: ["packages/core/src/radar/extractionSkill.ts"],
  },
  // Plan 7: the three research skills travel in researchInput (RESEARCH_SKILL_TEXT in relay/prompts.ts).
  { skill: "rlr-show-notes", name: "SHOW_NOTES_SKILL_TEXT", what: "how to research show notes", outs: ["packages/core/src/research/skills.ts"] },
  { skill: "rlr-pre-air-verify", name: "VERIFY_SKILL_TEXT", what: "how to check notes before air", outs: ["packages/core/src/research/skills.ts"] },
  { skill: "rlr-deep-dive", name: "DEEP_DIVE_SKILL_TEXT", what: "how to research a deep dive", outs: ["packages/core/src/research/skills.ts"] },
];

// Several skills may share one out file: each file is written once, with one constant per skill.
const files = new Map();
for (const { skill, name, what, outs } of SKILLS) {
  const md = readFileSync(new URL(`skills/${skill}/SKILL.md`, root), "utf8");
  const body = md.replace(/^---\n[\s\S]*?\n---\n/, "").trim();
  const literal = "`" + body.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${") + "`";
  const constant = `/** The ${skill} skill without its frontmatter: ${what}. */\nexport const ${name} = ${literal};\n`;
  for (const out of outs) files.set(out, [...(files.get(out) ?? []), { skill, constant }]);
}
for (const [out, entries] of files) {
  const from = entries.map((e) => `skills/${e.skill}/SKILL.md`).join(", ");
  writeFileSync(new URL(out, root), `// GENERATED by scripts/sync-description-skill.mjs from ${from}. Do not edit.\n${entries.map((e) => e.constant).join("\n")}`);
  console.log(`wrote ${out}`);
}
