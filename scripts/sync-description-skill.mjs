// Regenerates the description skill constant from skills/rlr-description-safety/SKILL.md (the one source).
// The relay and bridge ship as single bundles and Convex cannot read files, so the text travels as a TS string.
// Run `pnpm sync:skills` after editing the skill; packages/core/test/descriptionSkill.test.ts fails until you do.
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const md = readFileSync(new URL("skills/rlr-description-safety/SKILL.md", root), "utf8");
const body = md.replace(/^---\n[\s\S]*?\n---\n/, "").trim();
const literal = "`" + body.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${") + "`";
const file = `// GENERATED by scripts/sync-description-skill.mjs from skills/rlr-description-safety/SKILL.md. Do not edit.
/** The rlr-description-safety skill without its frontmatter: how to write a public Mixcloud description. */
export const DESCRIPTION_SKILL_TEXT = ${literal};
`;

// The bridge gets its own copy: it is built with tsc and deployed without @aircheck/core (a dev dependency).
for (const out of ["packages/core/src/package/descriptionSkill.ts", "apps/bridge/src/descriptionSkill.ts"]) {
  writeFileSync(new URL(out, root), file);
  console.log(`wrote ${out}`);
}
